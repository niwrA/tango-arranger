const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const cp=require('node:child_process');
let ts;try{ts=require('typescript')}catch{ts=require(path.join(cp.execFileSync('npm',['root','-g'],{encoding:'utf8'}).trim(),'typescript'));}
const code=ts.transpileModule(fs.readFileSync(path.join(__dirname,'../src/music.ts'),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const mod={exports:{}};
vm.runInNewContext(`(function(require,module,exports){${code}\n})`,{console},'music.ts')(()=>{throw Error('Unexpected import')},mod,mod.exports);
const m=mod.exports;
const p=m.demoProject();
const base=m.generate(p);
const inst='Violin I';
const source={...base,[inst]:[{pitch:55,start:0,duration:1}]};
const corrections=m.planAdaptiveTransposition(source,p,-2);
const violin=corrections.find(c=>c.instrument===inst&&c.originalPitch===55);
assert.equal(violin.intendedPitch,53);
assert.equal(violin.suggestedPitch,65);
assert.equal(violin.strategy,'octave');
const shifted={...p,transposeSemitones:-2,adaptiveTranspose:{enabled:true,chordToneRhythm:false,semitones:-2}};
const result=m.adaptTransposedScore(source,shifted);
assert.equal(result[inst][0].pitch,67);
assert.equal(source[inst][0].pitch,55,'source remains untouched');
assert.equal(m.adaptTransposedScore(source,p)[inst][0].pitch,55);
const protectedProject=m.demoProject();
protectedProject.importedScore={...base,[inst]:[{pitch:55,start:0,duration:1}]};
protectedProject.protectedBars={[`${inst}:0`]:true};
const changed=m.changeSectionKey(protectedProject,'A1','Cm','chords-and-melody',true);
assert.equal(changed.importedScore[inst][0].pitch,65);
assert.equal(protectedProject.importedScore[inst][0].pitch,55);
const app=fs.readFileSync(path.join(__dirname,'../src/App.vue'),'utf8');
assert.match(app,/__example_hasta_siempre__/);
assert.match(app,/h asta-siempre-amor\.json\?raw/.source.replace('h asta','hasta'));
assert.match(app,/planAdaptiveTransposition/);
console.log('PASS adaptive transposition and example registration');
