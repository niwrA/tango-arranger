const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const vm=require('node:vm');
const {ref,computed}=require('vue');
const app=fs.readFileSync('src/App.vue','utf8');
const section=app.match(/<details ref="leadLyricsPanel" class="lead-lyrics-workspace">[\s\S]*?<\/details>/)?.[0];
assert.ok(section,'native disclosure is available alongside both lead-sheet views');
assert.ok(section.includes('<summary>Lyrics &amp; chords · editable song source</summary>'));
assert.ok(!section.includes(':open=')&&!section.includes('<summary @click='),'no competing native and reactive open states');
const source=app.slice(app.indexOf('const leadVerseDrafts='),app.indexOf('const leadLyricsPlan='));
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const project=ref({leadLyrics:{'1':{source:'Saved verse one',useExistingMelody:true}}});
const {leadLyricsVerse,leadLyricsSource,leadLyricsUseMelody,leadVerseDrafts}=vm.runInNewContext(
 js+'\n;({leadLyricsVerse,leadLyricsSource,leadLyricsUseMelody,leadVerseDrafts})',{ref,computed,project,leadLyricsMatches:ref([])}
);
assert.equal(leadLyricsUseMelody.value,true);
leadLyricsSource.value='Draft verse one';
leadLyricsVerse.value=2;
assert.equal(leadLyricsSource.value,'');
leadLyricsSource.value='Draft verse two';
leadLyricsUseMelody.value=false;
leadLyricsVerse.value=1;
assert.equal(leadLyricsSource.value,'Draft verse one');
leadLyricsVerse.value=2;
assert.equal(leadLyricsSource.value,'Draft verse two');
assert.equal(leadLyricsUseMelody.value,false);
leadVerseDrafts.value={};
project.value={leadLyrics:{'1':{source:'Next song'}}};
assert.equal(leadLyricsSource.value,'');
leadLyricsVerse.value=1;
assert.equal(leadLyricsSource.value,'Next song');
console.log('PASS native Lyrics & Chords disclosure and per-song, per-verse drafts');
