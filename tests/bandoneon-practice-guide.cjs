const assert=require('node:assert/strict');
const {createDomainLoader}=require('./load-domain.cjs');
const {practiceBellowsFrame,practiceBellowsButtons}=createDomainLoader()('src/bandoneonPracticeGuide.ts');
const a={id:'left:A',hand:'left',x:0,y:0,pull:41,push:42};
const b={id:'right:B',hand:'right',x:0,y:0,pull:60,push:61};
const c={id:'left:C',hand:'left',x:1,y:0,pull:42,push:43};
const first={start:0,end:1,direction:'pull',buttons:[a,b]};
const second={start:1,end:2,direction:'push',buttons:[a,b,c]};
const conflict={start:3,end:4,direction:null,buttons:[]};
const frames=[first,second,conflict];
assert.equal(practiceBellowsFrame(frames,null),undefined);
assert.equal(practiceBellowsFrame(frames,-1),undefined);
assert.equal(practiceBellowsFrame(frames,0),first);
assert.equal(practiceBellowsFrame(frames,1),second,'a reversal uses the newly sounding button pitches');
assert.equal(practiceBellowsFrame(frames,2),undefined,'a rest does not retain the held keys');
assert.equal(practiceBellowsFrame(frames,3),conflict,'conflict is distinct from rest');
assert.deepEqual(practiceBellowsButtons(first,60),{active:[a,b],focus:[b]});
assert.deepEqual(practiceBellowsButtons(first,41,'left'),{active:[a],focus:[a]});
assert.deepEqual(practiceBellowsButtons(first,41,'right'),{active:[b],focus:[]});
assert.deepEqual(practiceBellowsButtons(second,61),{active:[a,b,c],focus:[b]});
assert.deepEqual(practiceBellowsButtons(second,60),{active:[a,b,c],focus:[]},'focus uses sounding direction, not both button pitches');
assert.deepEqual(practiceBellowsButtons(conflict,60),{active:[],focus:[]});
assert.equal(practiceBellowsFrame([{...first,reversalGap:.04},second],.98),undefined,'the bellows reversal gap is silent');
console.log('PASS physical Learn follows released keys, reversals and staff-filtered targets');
