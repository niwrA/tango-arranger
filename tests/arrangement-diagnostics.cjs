const assert=require('node:assert/strict');
const {createDomainLoader}=require('./load-domain.cjs');
const load=createDomainLoader(),m=load('src/music.ts'),d=load('src/arrangementDiagnostics.ts');
const p=m.blankProject({sections:1,measuresPerSection:3,beats:4,bpm:120});
p.bars.forEach(b=>b.chord='Dm');p.roles.A.Piano='chords';p.profile='darienzo';
const score=m.generate(p);
const before=JSON.stringify({p,score});
const findings=d.diagnoseArrangement(p,score);
assert.equal(JSON.stringify({p,score}),before,'scan must be read-only');
assert.ok(d.diagnoseArrangement(p,score,{instrument:'Piano',from:0,to:0}).every(x=>x.instrument==='Piano'&&x.measure===0));
assert.equal(d.refineArrangement(p,score,[]),p);
const noteIndex=score.Piano.findIndex(n=>n.start>=0&&n.start<4);
assert.ok(noteIndex>=0);
const issue={id:'test',category:'dynamics',severity:'suggestion',instrument:'Piano',measure:0,message:'test',noteIndex,patch:{velocity:63}};
const protectedProject={...p,protectedBars:{...p.protectedBars,'Piano:0':true}};
assert.equal(d.refineArrangement(protectedProject,score,[issue]),protectedProject);
const next=d.refineArrangement(p,score,[issue]);
assert.equal(JSON.stringify({p,score}),before,'correction must not mutate source');
const notesByPosition=notes=>JSON.parse(JSON.stringify(notes)).sort((a,b)=>a.start-b.start||a.pitch-b.pitch||a.duration-b.duration);
assert.deepEqual(notesByPosition(next.generatedScore.Piano),notesByPosition(score.Piano.map((n,i)=>i===noteIndex?{...n,velocity:63,source:'manual'}:n)));
assert.equal(next.generatedScore.Piano.find(n=>n.pitch===50&&n.start===0).velocity,63);
for(const [inst,notes] of Object.entries(score))if(inst!=='Piano')assert.deepEqual(notesByPosition(next.generatedScore[inst]),notesByPosition(notes));
assert.ok(next.protectedBars['Piano:0']);
if(findings.length){
 const dismissed={...p,dismissedArrangementFindings:[findings[0].id]};
 assert.ok(!d.diagnoseArrangement(dismissed,score).some(x=>x.id===findings[0].id));
 assert.ok(d.diagnoseArrangement(dismissed,score,{showDismissed:true}).some(x=>x.id===findings[0].id));
}
assert.ok(!d.diagnoseArrangement(p,score).some(x=>x.voicing||x.patch?.pitch!==undefined||x.patch?.start!==undefined));
console.log('PASS arrangement review read-only scan, scope, protected measures, expression preservation and dismissal');

const n=(pitch,start=0,duration=1,fields={})=>({pitch,start,duration,velocity:80,...fields});
const violin={...p,instruments:['Violin I'],adaptiveTranspose:{enabled:false,semitones:2,chordToneRhythm:false}};
const rangeFinding=(part,project,partNotes)=>d.diagnoseArrangement(project,{[part]:partNotes}).some(x=>x.category==='pitch'&&x.instrument===part);
assert.ok(!rangeFinding('Violin I',violin,[n(96)]));
assert.ok(rangeFinding('Violin I',{...violin,transposeSemitones:2},[n(96)]));
assert.ok(!rangeFinding('Violin I',{...violin,transposeSemitones:2,adaptiveTranspose:{enabled:true,semitones:2,chordToneRhythm:false,parts:{'Violin I':{strategy:'whole',octaves:-12}}}},[n(96)]));
const band={...p,instruments:['Bandoneon I']};
const map=load('src/bandoneon.ts');
const model=map.bandoneonModelForPart(band,'Bandoneon I');
const pair=Array.from({length:128},(_,pitch)=>pitch).find(pitch=>map.isBandoneonPitchPlayable(pitch,model,'right')&&map.isBandoneonPitchPlayable(pitch-1,model)&&!map.isBandoneonPitchPlayable(pitch-1,model,'right'));
assert.ok(pair!==undefined);
const handFinding=(shift)=>d.diagnoseArrangement({...band,transposeSemitones:shift},{'Bandoneon I':[n(pair,0,1,{staffOverride:1})]}).some(x=>x.category==='playability'&&x.message.includes('assigned right'));
assert.equal(handFinding(0),false);assert.equal(handFinding(-1),true);
const crossing={...p,protectedBars:{'Piano:1':true}};
const crossingScore={...score,Piano:[n(65,3,2)]};
assert.equal(d.canRefineArrangementFinding(crossing,crossingScore,issue),false);
assert.equal(d.refineArrangement(crossing,crossingScore,[issue]),crossing);
assert.equal(d.refineArrangement(crossing,crossingScore,[issue],true).generatedScore.Piano[0].velocity,63);
const conflictScore={...score,Piano:[n(65),n(67)]};
const relocate={...issue,patch:{pitch:67}};
assert.throws(()=>d.refineArrangement(p,conflictScore,[relocate]),/duplicate attack/);
assert.throws(()=>d.refineArrangement(p,conflictScore,[relocate,{...relocate,patch:{pitch:69}}]),/conflict/);
console.log('PASS sounding range with transpose and adaptation, assigned bandoneon hand, protected sustained notes and batch conflicts');
