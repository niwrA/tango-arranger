const assert=require('node:assert/strict');
const {createDomainLoader}=require('./load-domain.cjs');
const load=createDomainLoader(),m=load('src/music.ts'),d=load('src/arrangementDiagnostics.ts');
const p=m.blankProject({sections:1,measuresPerSection:2,beats:4,bpm:120});
p.profile='darienzo';p.bars.forEach(b=>b.chord='C');p.roles.A.Piano='chords';
const score=Object.fromEntries(m.projectInstruments(p).map(inst=>[inst,[]]));
score.Piano=[{pitch:64,start:0,duration:1,velocity:45,gate:.9},{pitch:67,start:1,duration:1,velocity:70},{pitch:64,start:2,duration:1,velocity:70},{pitch:67,start:3,duration:1,velocity:70}];
score['Violin I']=[{pitch:20,start:0,duration:1,velocity:80}];
const before=JSON.stringify([p,score]);
const findings=d.diagnoseArrangement(p,score);
assert.equal(JSON.stringify([p,score]),before,'scan must be read only');
assert.ok(findings.some(f=>f.category==='pitch'&&f.instrument==='Violin I'));
const fix=findings.find(f=>f.instrument==='Piano'&&f.category==='style'&&f.patch);
assert.ok(fix,'style expression proposal');
const refined=d.refineArrangement(p,score,[fix]);
assert.deepEqual(refined.generatedScore.Piano.map(n=>[n.pitch,n.start,n.duration]),score.Piano.map(n=>[n.pitch,n.start,n.duration]));
assert.notEqual(refined.generatedScore.Piano[fix.noteIndex].velocity,score.Piano[fix.noteIndex].velocity);
const protectedProject={...p,protectedBars:{'Piano:0':true}};
assert.equal(d.refineArrangement(protectedProject,score,[fix]),protectedProject);
assert.ok(d.diagnoseArrangement(p,score,{instrument:'Piano'}).every(f=>f.instrument==='Piano'));
assert.ok(d.diagnoseArrangement(p,score,{includeStyle:false}).every(f=>f.category!=='style'));
console.log('Arrangement diagnostics safety checks passed');
