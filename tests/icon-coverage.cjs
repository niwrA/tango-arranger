const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const icon = fs.readFileSync(path.join(root, 'src', 'AppIcon.vue'), 'utf8');
const vue = fs.readFileSync(path.join(root, 'src', 'App.vue'), 'utf8');
const signature = icon.match(/defineProps<\{name:([^}]+)\}>\(\)/);
assert.ok(signature, 'AppIcon should declare a typed name union');
const allowed = new Set([...signature[1].matchAll(/'([^']+)'/g)].map(m => m[1]));
const pathBlock = icon.match(/const paths:Record<typeof props\.name,string>=\{([\s\S]*?)\n\};/);
assert.ok(pathBlock, 'AppIcon should provide a path for each declared icon');
const defined = new Set([...pathBlock[1].matchAll(/^\s*(?:'([^']+)'|([a-z][\w-]*))\s*:/gm)].map(m => m[1] || m[2]));
const used = new Set([...vue.matchAll(/<AppIcon\s+name="([^"]+)"/g)].map(m => m[1]));
assert.ok(used.has('circle-help'), 'The help button must be included in coverage');
assert.deepEqual([...used].filter(x => !allowed.has(x)), [], 'Every template icon name must be declared');
assert.deepEqual([...allowed].filter(x => !defined.has(x)), [], 'Every declared icon must have a drawing path');
assert.deepEqual([...defined].filter(x => !allowed.has(x)), [], 'Every drawing path must have a declared name');
assert.equal(require('../package.json').version, '5.4.2');
console.log('PASS all', used.size, 'used icons are declared and drawn');
console.log('PASS', allowed.size, 'declared icons match their drawing paths');
console.log('PASS version 5.4.2');
