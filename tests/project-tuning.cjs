const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const code=fs.readFileSync('src/instrumentTuning.ts','utf8');
const js=ts.transpileModule(code,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const moduleObj={exports:{}};
new Function('module','exports',js)(moduleObj,moduleObj.exports);
const {DEFAULT_A4_HZ,validReferenceHz,tuningReferenceFor}=moduleObj.exports;
assert.equal(DEFAULT_A4_HZ,442);
assert.equal(tuningReferenceFor({},'Voice'),442);
assert.equal(tuningReferenceFor({},'Violin I'),442);
assert.equal(tuningReferenceFor({},'Bandoneon II'),442);
assert.equal(tuningReferenceFor({tuning:{a4Hz:440}},'Voice'),440);
assert.equal(tuningReferenceFor({tuning:{a4Hz:443,overrides:{'Violin I':441}}},'Violin I'),441);
assert.equal(tuningReferenceFor({tuning:{a4Hz:443,overrides:{'Violin I':441}}},'Violin II'),443);
assert.equal(tuningReferenceFor({tuning:{a4Hz:442,overrides:{'Violin I':900}}},'Violin I'),442);
assert.equal(tuningReferenceFor({tuning:{a4Hz:0}},'Piano'),442);
assert.equal(validReferenceHz(442),true);
assert.equal(validReferenceHz(442.5),false);
assert.equal(validReferenceHz(NaN),false);
const app=fs.readFileSync('src/App.vue','utf8');
const music=fs.readFileSync('src/music.ts','utf8');
const learn=fs.readFileSync('src/InstrumentLearnView.vue','utf8');
assert.match(music,/tuning\?:\{a4Hz:number;overrides\?:Record<string,number>\}/);
assert.match(app,/function setProjectA4Reference\(event:Event\)/);
assert.match(app,/function setInstrumentA4Reference\(inst:string,event:Event\)/);
assert.match(app,/if\(!raw\)\{delete overrides\[inst\];\}/);
assert.match(app,/aria-label="Project-wide A4 tuning reference in Hz"/);
assert.match(app,/class="roster-tuning-override"/);
assert.match(app,/:reference-hz="tuningReferenceFor\(project,part.inst\)"/);
assert.match(learn,/referenceHz=computed\(\(\)=>props.referenceHz\)/);
assert.doesNotMatch(learn,/props.instrument.startsWith\('Violin'\)\?442:440/);
assert.doesNotMatch(learn,/v-model.number="referenceHz"/);
assert.match(learn,/A4 tuning: <strong>\{\{referenceHz\}\} Hz/);
assert.doesNotMatch(app,/function setProjectA4Reference[\s\S]{0,1000}transposeSemitones\s*=/);
console.log('Project A4 default, per-part overrides and Learn reference tests passed');
